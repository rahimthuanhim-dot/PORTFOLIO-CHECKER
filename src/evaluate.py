"""Build blind human-label templates and evaluate the matcher vs. baseline.

No human labels are generated. The optional threshold tuner uses only the
disjoint synthetic development split and its source ``true_skills`` labels.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import random
import sys
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "data"
RESULTS_DIR = ROOT / "results"
STUDENTS_FILE = DATA_DIR / "students.csv"
INTERNSHIPS_FILE = DATA_DIR / "internships.csv"
RELEVANCE_FILE = RESULTS_DIR / "relevance_labels_template.csv"
RELEVANCE_KEY_FILE = RESULTS_DIR / "relevance_labels_key.csv"
EXTRACTION_FILE = RESULTS_DIR / "extraction_labels_template.csv"
GAP_FILE = RESULTS_DIR / "gap_rating_template.csv"
DEV_FILE = RESULTS_DIR / "dev_split_synthetic.csv"
CONFIG_FILE = RESULTS_DIR / "evaluation_config.json"
METRICS_FILE = RESULTS_DIR / "metrics.json"
WEB_METRICS_FILE = ROOT / "web" / "metrics.json"
SEED = 20261117
SAMPLE_SIZE = 50
DEFAULT_THRESHOLD = 0.55
THRESHOLD_GRID = (0.30, 0.35, 0.40, 0.45, 0.50, 0.55, 0.60, 0.65, 0.70, 0.75)

sys.path.insert(0, str(ROOT / "src"))
from baseline import rank_baseline  # noqa: E402
from extractor import extract_skills  # noqa: E402
from matcher import extract_posting_skill_sets, missing_skill_groups, rank_matcher  # noqa: E402


def read_csv(path: Path) -> list[dict[str, str]]:
    if not path.exists():
        raise FileNotFoundError(f"Required data file not found: {path}")
    with path.open(newline="", encoding="utf-8-sig") as stream:
        return list(csv.DictReader(stream))


def write_csv(path: Path, rows: list[dict[str, Any]], columns: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=columns)
        writer.writeheader()
        writer.writerows(rows)


def stable_id(prefix: str, value: str) -> str:
    digest = hashlib.sha256(value.encode("utf-8")).hexdigest()[:12].upper()
    return f"{prefix}{digest}"


def _sample_data():
    source_students = read_csv(STUDENTS_FILE)
    internships = read_csv(INTERNSHIPS_FILE)
    if len(source_students) < SAMPLE_SIZE * 2:
        raise ValueError(
            f"Need at least {SAMPLE_SIZE * 2} student profiles for separate evaluation and development splits; "
            f"found {len(source_students)}"
        )
    students = [dict(row, student_id=f"S{index:06d}") for index, row in enumerate(source_students, start=1)]
    shuffled = random.Random(SEED).sample(students, len(students))
    evaluation_students = shuffled[:SAMPLE_SIZE]
    dev_students = shuffled[SAMPLE_SIZE:SAMPLE_SIZE * 2]
    return students, internships, evaluation_students, dev_students


def _write_dev_split(dev_students: list[dict[str, str]]) -> None:
    rows = [{
        "student_id": student["student_id"],
        "profile": student["profile"],
        "synthetic_true_skills": student["true_skills"],
        "data_notice": "SYNTHETIC source data; true_skills generated by src/generate_data.py",
    } for student in dev_students]
    write_csv(DEV_FILE, rows, ["student_id", "profile", "synthetic_true_skills", "data_notice"])


def _read_dev_split() -> list[dict[str, str]]:
    return [{
        "student_id": row["student_id"],
        "profile": row["profile"],
        "true_skills": row["synthetic_true_skills"],
    } for row in read_csv(DEV_FILE)]


def _tune_threshold(dev_students: list[dict[str, str]]) -> tuple[float, float, list[dict[str, float]]]:
    """Select threshold by micro-F1 on synthetic labels from dev students only."""
    if not dev_students:
        raise ValueError("The synthetic development split is empty")
    results = []
    for threshold in THRESHOLD_GRID:
        true_positive = false_positive = false_negative = 0
        for student in dev_students:
            truth = {skill.strip() for skill in student["true_skills"].split("|") if skill.strip()}
            predicted = {item["skill"] for item in extract_skills(student["profile"], method="hybrid", threshold=threshold)}
            true_positive += len(predicted & truth)
            false_positive += len(predicted - truth)
            false_negative += len(truth - predicted)
        precision = true_positive / (true_positive + false_positive) if true_positive + false_positive else 0.0
        recall = true_positive / (true_positive + false_negative) if true_positive + false_negative else 0.0
        f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
        results.append({"threshold": threshold, "precision": precision, "recall": recall, "f1": f1})
    # Tie-break toward the stricter cutoff to prefer fewer unsupported matches.
    best = max(results, key=lambda row: (row["f1"], row["threshold"]))
    return best["threshold"], best["f1"], results


def _save_config(threshold: float, dev_f1: float | None = None) -> None:
    config: dict[str, Any] = {
        "embedding_model": "all-MiniLM-L6-v2",
        "similarity_threshold": threshold,
    }
    if dev_f1 is not None:
        config["threshold_tuning"] = {
            "source": "results/dev_split_synthetic.csv",
            "objective": "micro-F1 against synthetic_true_skills",
            "dev_micro_f1": dev_f1,
        }
    CONFIG_FILE.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")


def _load_threshold(explicit_threshold: float | None) -> float:
    if explicit_threshold is not None:
        return explicit_threshold
    if CONFIG_FILE.exists():
        try:
            config = json.loads(CONFIG_FILE.read_text(encoding="utf-8"))
            value = float(config["similarity_threshold"])
            if 0.0 <= value <= 1.0:
                return value
        except (OSError, ValueError, KeyError, TypeError, json.JSONDecodeError):
            pass
    return DEFAULT_THRESHOLD


def _rankings(
    evaluation_students: list[dict[str, str]],
    internships: list[dict[str, str]],
    threshold: float,
):
    posting_skill_sets = extract_posting_skill_sets(internships, threshold, extract_skills)
    ranked: dict[str, dict[str, list[dict[str, Any]]]] = {}
    for student in evaluation_students:
        student_id = student["student_id"]
        student_skills = {
            item["skill"] for item in extract_skills(student["profile"], method="hybrid", threshold=threshold)
        }
        matcher_rows = rank_matcher(student_skills, internships, posting_skill_sets, top_k=5)
        baseline_rows = rank_baseline(student["profile"], internships, top_k=5)
        ranked[student_id] = {
            "matcher": [
                {"score": score, "internship_id": f"I{index + 1:06d}", "posting": internships[index], "index": index}
                for score, index in matcher_rows
            ],
            "baseline": [
                {"score": score, "internship_id": f"I{index + 1:06d}", "posting": internships[index], "index": index}
                for score, index in baseline_rows
            ],
        }
    return ranked, posting_skill_sets


def _create_relevance_templates(evaluation_students, ranked) -> None:
    student_by_id = {student["student_id"]: student for student in evaluation_students}
    template_rows: list[dict[str, str]] = []
    key_rows: list[dict[str, str]] = []
    for student_id, systems in ranked.items():
        pooled = []
        for system_name, candidates in systems.items():
            for rank, candidate in enumerate(candidates, start=1):
                private_key = f"{student_id}|{system_name}|{candidate['internship_id']}|{rank}"
                candidate_id = stable_id("C", private_key)
                pooled.append((candidate_id, system_name, rank, candidate))
        random.Random(f"{SEED}:{student_id}:shuffle").shuffle(pooled)
        student = student_by_id[student_id]
        for candidate_id, system_name, rank, candidate in pooled:
            posting = candidate["posting"]
            template_rows.append({
                "student_id": student_id,
                "student_profile": student["profile"],
                "candidate_id": candidate_id,
                "internship_title": posting["title"],
                "company": posting["company"],
                "description": posting["description"],
                "relevant": "",
                "annotator": "",
            })
            key_rows.append({
                "candidate_id": candidate_id,
                "system": system_name,
                "rank": rank,
                "internship_id": candidate["internship_id"],
            })
    random.Random(SEED).shuffle(template_rows)
    write_csv(RELEVANCE_FILE, template_rows, [
        "student_id", "student_profile", "candidate_id", "internship_title", "company", "description", "relevant", "annotator",
    ])
    write_csv(RELEVANCE_KEY_FILE, key_rows, ["candidate_id", "system", "rank", "internship_id"])


def _create_extraction_template(evaluation_students, internships) -> None:
    rng = random.Random(SEED + 1)
    student_docs = rng.sample(evaluation_students, min(25, len(evaluation_students)))
    internship_docs = rng.sample(internships, min(25, len(internships)))
    rows: list[dict[str, str]] = []
    for student in student_docs:
        doc_id = stable_id("D", "student|" + student["student_id"])
        rows.append({
            "doc_id": doc_id,
            "document_type": "student_profile",
            "text": student["profile"],
            "true_skills": "",
            "annotator": "",
        })
    for posting in internship_docs:
        index = internships.index(posting) + 1
        posting_id = f"I{index:06d}"
        doc_id = stable_id("D", "internship|" + posting_id)
        rows.append({
            "doc_id": doc_id,
            "document_type": "internship_description",
            "text": posting["description"],
            "true_skills": "",
            "annotator": "",
        })
    rng.shuffle(rows)
    write_csv(EXTRACTION_FILE, rows, ["doc_id", "document_type", "text", "true_skills", "annotator"])


def _create_gap_template(evaluation_students, ranked, posting_skill_sets, threshold) -> None:
    student_by_id = {student["student_id"]: student for student in evaluation_students}
    rows = []
    for student_id in sorted(ranked):
        student = student_by_id[student_id]
        student_skills = {
            item["skill"] for item in extract_skills(student["profile"], method="hybrid", threshold=threshold)
        }
        best = ranked[student_id]["matcher"][0]
        posting = best["posting"]
        posting_skills = posting_skill_sets[best["index"]]
        gaps = missing_skill_groups(student_skills, posting, posting_skills)
        required_text = ", ".join(gaps["required"]) if gaps["required"] else "None detected"
        preferred_text = ", ".join(gaps["preferred"]) if gaps["preferred"] else "None detected"
        report = (
            f"Suggested posting: {posting['title']} at {posting['company']}. "
            f"Required skills extracted from the posting but not evidenced in the profile: {required_text}. "
            f"Preferred skills extracted from the posting but not evidenced in the profile: {preferred_text}."
        )
        rows.append({
            "student_id": student_id,
            "internship_id": best["internship_id"],
            "gap_report": report,
            "usefulness_rating": "",
            "annotator": "",
        })
    write_csv(GAP_FILE, rows, ["student_id", "internship_id", "gap_report", "usefulness_rating", "annotator"])


def _has_human_entries(path: Path) -> bool:
    if not path.exists():
        return False
    with path.open(newline="", encoding="utf-8-sig") as stream:
        reader = csv.DictReader(stream)
        label_columns = {
            RELEVANCE_FILE: ("relevant", "annotator"),
            EXTRACTION_FILE: ("true_skills", "annotator"),
            GAP_FILE: ("usefulness_rating", "annotator"),
        }.get(path, ())
        return any(any((row.get(column) or "").strip() for column in label_columns) for row in reader)


def _ensure_templates(evaluation_students, internships, threshold, regenerate=False) -> list[Path]:
    if regenerate:
        filled = [path for path in (RELEVANCE_FILE, EXTRACTION_FILE, GAP_FILE) if _has_human_entries(path)]
        if filled:
            names = ", ".join(str(path.relative_to(ROOT)) for path in filled)
            raise ValueError(f"Refusing to overwrite human entries in: {names}")
    created: list[Path] = []
    needs_rankings = regenerate or not RELEVANCE_FILE.exists() or not GAP_FILE.exists()
    ranked, posting_skill_sets = _rankings(evaluation_students, internships, threshold) if needs_rankings else (None, None)
    if regenerate or not RELEVANCE_FILE.exists():
        _create_relevance_templates(evaluation_students, ranked)
        created.append(RELEVANCE_FILE)
    if regenerate or not EXTRACTION_FILE.exists():
        _create_extraction_template(evaluation_students, internships)
        created.append(EXTRACTION_FILE)
    if regenerate or not GAP_FILE.exists():
        _create_gap_template(evaluation_students, ranked, posting_skill_sets, threshold)
        created.append(GAP_FILE)
    return created


def _read_labeled(path: Path, label_column: str) -> tuple[list[dict[str, str]], int, int]:
    rows = read_csv(path)
    blank_labels = sum(not row.get(label_column, "").strip() for row in rows)
    blank_annotators = sum(not row.get("annotator", "").strip() for row in rows)
    return rows, blank_labels, blank_annotators


def _require_complete_labels() -> dict[str, list[dict[str, str]]]:
    required = [RELEVANCE_FILE, EXTRACTION_FILE, GAP_FILE, RELEVANCE_KEY_FILE]
    missing = [path for path in required if not path.exists()]
    if missing:
        raise ValueError("Missing evaluation files: " + ", ".join(str(path.relative_to(ROOT)) for path in missing))
    relevance, relevance_blank, relevance_annotator_blank = _read_labeled(RELEVANCE_FILE, "relevant")
    extraction, extraction_blank, extraction_annotator_blank = _read_labeled(EXTRACTION_FILE, "true_skills")
    gaps, gap_blank, gap_annotator_blank = _read_labeled(GAP_FILE, "usefulness_rating")
    incomplete = []
    for path, blank_labels, blank_annotators in (
        (RELEVANCE_FILE, relevance_blank, relevance_annotator_blank),
        (EXTRACTION_FILE, extraction_blank, extraction_annotator_blank),
        (GAP_FILE, gap_blank, gap_annotator_blank),
    ):
        if blank_labels or blank_annotators:
            incomplete.append(f"{path.name}: {blank_labels} blank labels, {blank_annotators} blank annotator entries")
    if incomplete:
        raise ValueError("Human annotations are incomplete. Fill label and annotator columns; " + "; ".join(incomplete))
    return {"relevance": relevance, "extraction": extraction, "gaps": gaps, "key": read_csv(RELEVANCE_KEY_FILE)}


def _metrics(labeled: dict[str, list[dict[str, str]]], threshold: float) -> dict[str, Any]:
    relevance_rows = labeled["relevance"]
    key_by_id = {row["candidate_id"]: row for row in labeled["key"]}
    counts: dict[str, dict[str, dict[str, int]]] = {"matcher": {}, "baseline": {}}
    for row in relevance_rows:
        candidate_id = row["candidate_id"]
        if candidate_id not in key_by_id:
            raise ValueError(f"Candidate id {candidate_id!r} has no entry in the blind key")
        try:
            label = int(row["relevant"])
        except ValueError as exc:
            raise ValueError(f"Invalid relevance label for {candidate_id!r}; use 0 or 1") from exc
        if label not in {0, 1}:
            raise ValueError(f"Invalid relevance label for {candidate_id!r}; use 0 or 1")
        student_id = row["student_id"]
        system = key_by_id[candidate_id]["system"]
        if system not in counts:
            raise ValueError(f"Unknown system {system!r} for candidate {candidate_id!r}")
        record = counts[system].setdefault(student_id, {"relevant": 0, "count": 0})
        record["count"] += 1
        record["relevant"] += label
    precision_at_5 = {}
    for system in ("matcher", "baseline"):
        per_student = counts[system]
        if not per_student or any(entry["count"] != 5 for entry in per_student.values()):
            raise ValueError(f"Relevance labels must contain exactly five {system} candidates per student")
        precision_at_5[system] = sum(entry["relevant"] / 5 for entry in per_student.values()) / len(per_student)

    true_positive = {"dictionary": 0, "hybrid": 0}
    false_positive = {"dictionary": 0, "hybrid": 0}
    false_negative = {"dictionary": 0, "hybrid": 0}
    for row in labeled["extraction"]:
        truth = {skill.strip() for skill in row["true_skills"].split("|") if skill.strip()}
        if not truth:
            raise ValueError(f"No true skills entered for document {row['doc_id']!r}; use pipe-separated canonical names")
        for method in ("dictionary", "hybrid"):
            predicted = {
                item["skill"] for item in extract_skills(row["text"], method=method, threshold=threshold)
            }
            true_positive[method] += len(predicted & truth)
            false_positive[method] += len(predicted - truth)
            false_negative[method] += len(truth - predicted)
    extraction_metrics = {}
    for method in ("dictionary", "hybrid"):
        precision = true_positive[method] / (true_positive[method] + false_positive[method]) if true_positive[method] + false_positive[method] else 0.0
        recall = true_positive[method] / (true_positive[method] + false_negative[method]) if true_positive[method] + false_negative[method] else 0.0
        f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
        extraction_metrics[method] = {"precision": precision, "recall": recall, "f1": f1}

    ratings = []
    for row in labeled["gaps"]:
        try:
            rating = int(row["usefulness_rating"])
        except ValueError as exc:
            raise ValueError(f"Invalid usefulness rating for {row['student_id']!r}; enter an integer from 1 to 5") from exc
        if not 1 <= rating <= 5:
            raise ValueError(f"Invalid usefulness rating for {row['student_id']!r}; enter an integer from 1 to 5")
        ratings.append(rating)
    if not ratings:
        raise ValueError("No usefulness ratings were supplied")
    all_annotators = {
        row["annotator"].strip()
        for category in ("relevance", "extraction", "gaps")
        for row in labeled[category]
        if row["annotator"].strip()
    }
    return {
        "precision_at_5": precision_at_5,
        "skill_extraction": extraction_metrics,
        "mean_gap_usefulness_rating": sum(ratings) / len(ratings),
        "human_labeled_counts": {
            "relevance_candidates": len(relevance_rows),
            "students_rated_for_relevance": len({row["student_id"] for row in relevance_rows}),
            "extraction_documents": len(labeled["extraction"]),
            "gap_reports_rated": len(ratings),
            "annotators": len(all_annotators),
        },
        "configuration": {"embedding_model": "all-MiniLM-L6-v2", "similarity_threshold": threshold},
    }


def _print_comparison(metrics: dict[str, Any]) -> None:
    print("\nHuman-labeled evaluation comparison")
    print(f"{'Metric':<30} {'Matcher / hybrid':>18} {'Baseline / dictionary':>23}")
    print("-" * 75)
    print(f"{'Precision@5':<30} {metrics['precision_at_5']['matcher']:>18.4f} {metrics['precision_at_5']['baseline']:>23.4f}")
    for metric in ("precision", "recall", "f1"):
        print(f"{('Skill extraction ' + metric):<30} {metrics['skill_extraction']['hybrid'][metric]:>18.4f} {metrics['skill_extraction']['dictionary'][metric]:>23.4f}")
    print(f"{'Mean gap usefulness rating':<30} {metrics['mean_gap_usefulness_rating']:>18.4f} {'not rated':>23}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--threshold", type=float, default=None, help="Explicit embedding cutoff; overrides saved/default value.")
    parser.add_argument("--tune", action="store_true", help="Tune threshold using only the disjoint synthetic dev split.")
    parser.add_argument("--regenerate-templates", action="store_true", help="Rebuild blank templates; refuses to overwrite any labels or annotator entries.")
    args = parser.parse_args()
    if args.threshold is not None and not 0.0 <= args.threshold <= 1.0:
        parser.error("--threshold must be between 0 and 1")

    try:
        _, internships, evaluation_students, dev_students = _sample_data()
        if args.tune or args.regenerate_templates or not DEV_FILE.exists():
            _write_dev_split(dev_students)
        dev_f1 = None
        if args.tune:
            dev_split = _read_dev_split()
            threshold, dev_f1, _ = _tune_threshold(dev_split)
            _save_config(threshold, dev_f1)
            print(f"Tuned threshold from synthetic dev split only: {threshold:.2f}")
            print(f"Synthetic dev micro-F1 at selected threshold: {dev_f1:.4f}")
            print(f"Development students used: {len(dev_split)}; evaluation students held out: {len(evaluation_students)}")
        else:
            threshold = _load_threshold(args.threshold)
            if args.threshold is not None:
                _save_config(threshold)
        created = _ensure_templates(evaluation_students, internships, threshold, args.regenerate_templates)
        if created:
            print("Generated blank human-label templates:")
            for path in created:
                print(f"  {path.relative_to(ROOT)}")
        labeled = _require_complete_labels()
        metrics = _metrics(labeled, threshold)
    except (FileNotFoundError, ValueError, ImportError) as exc:
        print(f"Evaluation not run: {exc}", file=sys.stderr)
        print("No human labels or metrics were created. Fill the label and annotator columns, then rerun.", file=sys.stderr)
        return 2

    METRICS_FILE.write_text(json.dumps(metrics, indent=2) + "\n", encoding="utf-8")
    WEB_METRICS_FILE.write_text(json.dumps(metrics, indent=2) + "\n", encoding="utf-8")
    print(f"Saved computed metrics to {METRICS_FILE.relative_to(ROOT)}")
    print(f"Copied computed metrics to {WEB_METRICS_FILE.relative_to(ROOT)} for the static website")
    _print_comparison(metrics)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
